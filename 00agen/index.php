        filterButtons.forEach(button => {
            button.addEventListener('click', () => {
                // Remove active class from all buttons
                filterButtons.forEach(btn => btn.classList.remove('active'));
                // Add active class to clicked button
                button.classList.add('active');

                const filter = button.getAttribute('data-filter');

                testimonialCards.forEach(card => {
                    const cardParent = card.closest('.col-lg-4');
                    
                    if (filter === 'all') {
                        cardParent.style.display = 'block';
                    } else if (filter === '5' || filter === '4') {
                        if (card.getAttribute('data-rating') === filter) {
                            cardParent.style.display = 'block';
                        } else {
                            cardParent.style.display = 'none';
                        }
                    } else if (filter === 'buy' || filter === 'rent') {
                        if (card.getAttribute('data-category') === filter) {
                            cardParent.style.display = 'block';
                        } else {
                            cardParent.style.display = 'none';
                        }
                    }
                });

                // Re-trigger AOS animation for visible cards
                setTimeout(() => {
                    AOS.refresh();
                }, 100);
            });
        });

        // Smooth scrolling for internal links
