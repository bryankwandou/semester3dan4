        // Initialize AOS
        AOS.init();

        // Counter animation
        function animateCounter(element, start, end, duration) {
            const startTime = Date.now();
            const endTime = startTime + duration;

            function updateCounter() {
                const now = Date.now();
                const remaining = Math.max((endTime - now) / duration, 0);
                const value = Math.round(end - (remaining * (end - start)));
                element.textContent = value;

                if (value < end) {
                    requestAnimationFrame(updateCounter);
                }
            }

            updateCounter();
        }

        // Trigger counter animation when element comes into view
        const counters = document.querySelectorAll('.purecounter');
        const observerOptions = {
            threshold: 0.7
        };

        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    const counter = entry.target;
                    const endValue = parseInt(counter.getAttribute('data-purecounter-end'));
                    animateCounter(counter, 0, endValue, 2000);
                    observer.unobserve(counter);
                }
            });
        }, observerOptions);

        counters.forEach(counter => observer.observe(counter));
    </script>
