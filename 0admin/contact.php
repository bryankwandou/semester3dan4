        // Initialize AOS
        AOS.init({
            duration: 1000,
            once: true
        });

        // Global variables
        let map;
        let directionsService;
        let directionsRenderer;
        let currentMapType = 'roadmap';
        let currentTransportMode = 'DRIVING';
        let userLocation = null;
        
        // Destination coordinates (Downtown Conference Center)
        const destination = {
            lat: 40.710059,
            lng: -74.006138
        };

        // Initialize Google Maps
        function initMap() {
            // Create map
            map = new google.maps.Map(document.getElementById('map'), {
                zoom: 15,
                center: destination,
                mapTypeId: currentMapType,
                styles: [
                    {
                        featureType: "poi",
                        elementType: "labels",
                        stylers: [{ visibility: "on" }]
                    }
                ],
                mapTypeControl: false,
                streetViewControl: true,
                fullscreenControl: true,
                zoomControl: true
            });

            // Initialize directions service and renderer
            directionsService = new google.maps.DirectionsService();
            directionsRenderer = new google.maps.DirectionsRenderer({
                draggable: true,
                panel: document.getElementById('routeDetails')
            });
            directionsRenderer.setMap(map);

            // Add destination marker
            const destinationMarker = new google.maps.Marker({
                position: destination,
                map: map,
                title: 'Downtown Conference Center',
                icon: {
                    url: 'data:image/svg+xml;charset=UTF-8,' + encodeURIComponent(`
                        <svg width="40" height="40" viewBox="0 0 40 40" xmlns="http://www.w3.org/2000/svg">
                            <circle cx="20" cy="20" r="18" fill="#667eea" stroke="white" stroke-width="3"/>
                            <text x="20" y="26" text-anchor="middle" fill="white" font-size="16" font-weight="bold">📍</text>
                        </svg>
                    `),
                    scaledSize: new google.maps.Size(40, 40)
                },
                animation: google.maps.Animation.BOUNCE
            });

            // Add info window to destination marker
            const infoWindow = new google.maps.InfoWindow({
                content: `
                    <div style="padding: 10px; max-width: 300px;">
                        <h6 style="margin: 0 0 10px 0; color: #333;">
                            <i class="fas fa-building"></i>
                            Downtown Conference Center
                        </h6>
                        <p style="margin: 5px 0; color: #666;">
                            <i class="fas fa-map-marker-alt"></i>
                            123 Conference St, New York, NY 10013
                        </p>
                        <p style="margin: 5px 0; color: #666;">
                            <i class="fas fa-phone"></i>
                            +1 (555) 123-4567
                        </p>
                        <div style="margin-top: 10px;">
                            <button onclick="getDirections()" class="btn btn-sm btn-primary">
                                <i class="fas fa-directions"></i> Get Directions
                            </button>
                        </div>
                    </div>
                `
            });

            destinationMarker.addListener('click', () => {
                infoWindow.open(map, destinationMarker);
            });

            updateStatus('Ready', 'success');
        }

        // Change map type
        function changeMapType(type) {
            currentMapType = type;
            map.setMapTypeId(type);
            
            // Update active button
            document.querySelectorAll('.btn-view').forEach(btn => btn.classList.remove('active'));
            document.getElementById(type + 'Btn').classList.add('active');
            
            updateStatus(`Switched to ${type} view`, 'success');
        }

        // Change transport mode
        function changeTransportMode(mode) {
            currentTransportMode = mode;
            
            // Update active button
            document.querySelectorAll('.btn-transport').forEach(btn => btn.classList.remove('active'));
            
            const buttonMap = {
                'DRIVING': 'drivingBtn',
                'TWO_WHEELER': 'motorcycleBtn', 
                'WALKING': 'walkingBtn',
                'TRANSIT': 'transitBtn'
            };
            
            document.getElementById(buttonMap[mode]).classList.add('active');
            
            // If route is already shown, recalculate with new mode
            if (userLocation) {
                calculateAndDisplayRoute(userLocation, destination);
            }
            
            const modeNames = {
                'DRIVING': 'Mobil',
                'TWO_WHEELER': 'Motor',
                'WALKING': 'Jalan Kaki',
                'TRANSIT': 'Transit'
            };
            
            updateStatus(`Transportation mode: ${modeNames[mode]}`, 'success');
        }

        // Get current user location
        function getCurrentLocation() {
            updateStatus('Getting your location...', 'loading');
            
            if (navigator.geolocation) {
                navigator.geolocation.getCurrentPosition(
                    (position) => {
                        userLocation = {
                            lat: position.coords.latitude,
                            lng: position.coords.longitude
                        };
                        
                        // Add user location marker
                        if (window.userMarker) {
                            window.userMarker.setMap(null);
                        }
                        
                        window.userMarker = new google.maps.Marker({
                            position: userLocation,
                            map: map,
                            title: 'Your Location',
                            icon: {
                                url: 'data:image/svg+xml;charset=UTF-8,' + encodeURIComponent(`
                                    <svg width="30" height="30" viewBox="0 0 30 30" xmlns="http://www.w3.org/2000/svg">
                                        <circle cx="15" cy="15" r="12" fill="#28a745" stroke="white" stroke-width="3"/>
                                        <circle cx="15" cy="15" r="4" fill="white"/>
                                    </svg>
                                `),
                                scaledSize: new google.maps.Size(30, 30)
                            }
                        });
                        
                        // Center map to show both locations
                        const bounds = new google.maps.LatLngBounds();
                        bounds.extend(userLocation);
                        bounds.extend(destination);
                        map.fitBounds(bounds);
                        
                        updateStatus('Location found!', 'success');
                    },
                    (error) => {
                        let errorMessage = 'Unable to get location: ';
                        switch(error.code) {
                            case error.PERMISSION_DENIED:
                                errorMessage += 'Permission denied';
                                break;
                            case error.POSITION_UNAVAILABLE:
                                errorMessage += 'Position unavailable';
                                break;
                            case error.TIMEOUT:
                                errorMessage += 'Request timeout';
                                break;
                        }
                        updateStatus(errorMessage, 'error');
                    },
                    {
                        enableHighAccuracy: true,
                        timeout: 10000,
                        maximumAge: 600000
                    }
                );
            } else {
                updateStatus('Geolocation not supported', 'error');
            }
        }

        // Get directions
        function getDirections() {
            if (!userLocation) {
                getCurrentLocation();
                setTimeout(() => {
                    if (userLocation) {
                        calculateAndDisplayRoute(userLocation, destination);
                    }
                }, 2000);
            } else {
                calculateAndDisplayRoute(userLocation, destination);
            }
        }

        // Calculate and display route
        function calculateAndDisplayRoute(origin, destination) {
            updateStatus('Calculating route...', 'loading');
            
            const request = {
                origin: origin,
                destination: destination,
                travelMode: google.maps.TravelMode[currentTransportMode],
                avoidHighways: false,
                avoidTolls: false,
                optimizeWaypoints: true
            };

            directionsService.route(request, (result, status) => {
                if (status === 'OK') {
                    directionsRenderer.setDirections(result);
                    
                    // Show route information
                    const route = result.routes[0];
                    const leg = route.legs[0];
                    
                    document.getElementById('routeInfo').classList.add('show');
                    document.getElementById('routeDetails').innerHTML = `
                        <div class="row">
                            <div class="col-md-6">
                                <p><strong><i class="fas fa-route"></i> Distance:</strong> ${leg.distance.text}</p>
                                <p><strong><i class="fas fa-clock"></i> Duration:</strong> ${leg.duration.text}</p>
                            </div>
                            <div class="col-md-6">
                                <p><strong><i class="fas fa-map-marker-alt"></i> From:</strong> ${leg.start_address}</p>
                                <p><strong><i class="fas fa-flag-checkered"></i> To:</strong> ${leg.end_address}</p>
                            </div>
                        </div>
                        <div class="mt-3">
                            <button class="btn btn-primary btn-sm" onclick="openInGoogleMaps()">
                                <i class="fas fa-external-link-alt"></i>
                                Open in Google Maps
                            </button>
                            <button class="btn btn-success btn-sm" onclick="shareRoute()">
                                <i class="fas fa-share"></i>
                                Share Route
                            </button>
                        </div>
                    `;
                    
                    updateStatus(`Route calculated: ${leg.distance.text}, ${leg.duration.text}`, 'success');
                } else {
                    updateStatus('Could not calculate route: ' + status, 'error');
                }
            });
        }

        // Clear route
        function clearRoute() {
            directionsRenderer.setDirections({routes: []});
            document.getElementById('routeInfo').classList.remove('show');
            
            // Remove user marker
            if (window.userMarker) {
                window.userMarker.setMap(null);
            }
            
            userLocation = null;
            
            // Reset map view
            map.setCenter(destination);
            map.setZoom(15);
            
            updateStatus('Route cleared', 'success');
        }

        // Open in Google Maps app
        function openInGoogleMaps() {
            if (userLocation) {
                const url = `https://www.google.com/maps/dir/${userLocation.lat},${userLocation.lng}/${destination.lat},${destination.lng}/@${destination.lat},${destination.lng},15z/data=!3m1!4b1!4m2!4m1!3e${getGoogleMapsTravelMode()}`;
                window.open(url, '_blank');
            } else {
                const url = `https://www.google.com/maps/search/?api=1&query=${destination.lat},${destination.lng}`;
                window.open(url, '_blank');
            }
        }

        // Get Google Maps travel mode code
        function getGoogleMapsTravelMode() {
            const modes = {
                'DRIVING': '0',
                'TWO_WHEELER': '0', // Google Maps doesn't have separate motorcycle mode
                'WALKING': '2',
                'TRANSIT': '3'
            };
            return modes[currentTransportMode] || '0';
        }

        // Share route
        function shareRoute() {
            if (navigator.share && userLocation) {
                navigator.share({
                    title: 'Route to Downtown Conference Center',
                    text: 'Check out this route I found!',
                    url: `https://www.google.com/maps/dir/${userLocation.lat},${userLocation.lng}/${destination.lat},${destination.lng}`
                });
            } else {
                // Fallback to copying to clipboard
                const url = userLocation ? 
                    `https://www.google.com/maps/dir/${userLocation.lat},${userLocation.lng}/${destination.lat},${destination.lng}` :
