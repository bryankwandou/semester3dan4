        function applyFilters() {
            const searchTerm = document.getElementById('searchFilter').value.toLowerCase();
            const typeFilter = document.getElementById('typeFilter').value;
            const statusFilter = document.getElementById('statusFilter').value;
            const cityFilter = document.getElementById('cityFilter').value;
            const minPrice = parseFloat(document.getElementById('minPrice').value) || 0;
            const maxPrice = parseFloat(document.getElementById('maxPrice').value) || Infinity;

            filteredData = propertyData.filter(property => {
                const matchSearch = property.headline.toLowerCase().includes(searchTerm) ||
                                  property.city.toLowerCase().includes(searchTerm) ||
                                  property.agent_name.toLowerCase().includes(searchTerm);
                const matchType = !typeFilter || property.property_type === typeFilter;
                const matchStatus = !statusFilter || property.availability_status === statusFilter;
                const matchCity = !cityFilter || property.city === cityFilter;
                const matchPrice = property.price >= minPrice && property.price <= maxPrice;

                return matchSearch && matchType && matchStatus && matchCity && matchPrice;
            });

            currentPage = 1;
            renderTable();
        }

